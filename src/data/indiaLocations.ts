// Cached location dictionary to prevent redundant remote requests
let cachedLocations: Record<string, string[]> = { ...ALL_INDIAN_STATES_DISTRICTS };
let isFetchedFromSupabase = false;

/**
 * Fetch and merge Indian states & districts from Supabase
 * Tries direct location table, then queries live tournaments table in Supabase
 */
export async function getIndianLocationsFromSupabase(): Promise<Record<string, string[]>> {
  if (isFetchedFromSupabase) {
    return cachedLocations;
  }

  const client = getSupabase();
  if (!client) {
    return cachedLocations;
  }

  try {
    // 1. Check if a dedicated 'locations' or 'india_locations' table exists in Supabase
    const { data: locData, error: locError } = await client
      .from("locations")
      .select("state, district")
      .limit(500);

    if (!locError && locData && locData.length > 0) {
      locData.forEach((row: any) => {
        if (row.state && row.district) {
          const st = row.state.trim();
          const dist = row.district.trim();
          if (!cachedLocations[st]) cachedLocations[st] = [];
          if (!cachedLocations[st].includes(dist)) cachedLocations[st].push(dist);
        }
      });
      isFetchedFromSupabase = true;
      return cachedLocations;
    }

    // 2. Query distinct states and districts from the live Supabase tournaments table
    const { data: tourneyLocations, error: tourneyError } = await client
      .from("tournaments")
      .select("state, district")
      .not("state", "is", null);

    if (!tourneyError && tourneyLocations) {
      tourneyLocations.forEach((row: any) => {
        if (row.state) {
          const st = row.state.trim();
          const dist = row.district ? row.district.trim() : "";
          if (!cachedLocations[st]) cachedLocations[st] = [];
          if (dist && !cachedLocations[st].includes(dist)) {
            cachedLocations[st].push(dist);
          }
        }
      });
      isFetchedFromSupabase = true;
    }
  } catch (err) {
    console.warn("Notice: Using full integrated Indian states dataset:", err);
  }

  return cachedLocations;
}

/**
 * Returns list of all available states (alphabetically sorted, with Tamil Nadu & Telangana prioritized)
 */
export function getAvailableStates(): string[] {
  const states = Object.keys(cachedLocations);
  // Sort with Tamil Nadu at top (user preference), then others alphabetically
  return states.sort((a, b) => {
    if (a === "Tamil Nadu") return -1;
    if (b === "Tamil Nadu") return 1;
    if (a === "Telangana") return -1;
    if (b === "Telangana") return 1;
    return a.localeCompare(b);
  });
}

/**
 * Returns list of districts for a given state
 */
export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return [];
  const list = cachedLocations[stateName] || [];
  return [...list].sort();
}
